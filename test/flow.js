const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const page = await b.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto('file://' + path.resolve('dist/dweller.html'));
  await page.waitForFunction(() => window.__dweller);
  const st = () => page.evaluate(() => { const d = window.__dweller; return { mode: d.mode, level: d.level, beaten: d.progress.beaten.map(Number).join(''), fused: d.progress.fused }; });
  const winNow = () => page.evaluate(() => { const d = window.__dweller, w = d.world, s = d.state; s.grace = 1e9; d.teleport(w.goal.x - 2.5, w.goal.y - 5); });
  await page.evaluate(() => window.__dweller.setProgress({ beaten: [false, false, false, false, false, false], comp: false, cp: {}, fused: false, best: [0, 0, 0, 0, 0, 0] }));
  await page.keyboard.press('Space'); await page.waitForTimeout(300);
  console.log('1 title->map', JSON.stringify(await st()));
  await page.keyboard.press('ArrowDown'); await page.waitForTimeout(100); await page.keyboard.press('Space'); await page.waitForTimeout(300);
  console.log('2 locked II pressed', JSON.stringify(await st()));
  await page.keyboard.press('ArrowUp'); await page.keyboard.press('Space'); await page.waitForTimeout(500);
  console.log('3 play I', JSON.stringify(await st()));
  await winNow(); await page.waitForTimeout(3200);
  console.log('4 won I', JSON.stringify(await st()));
  await page.keyboard.press('Enter'); await page.waitForTimeout(1800);
  await page.screenshot({ path: 'shots/flow_map_after1.png' });
  console.log('5 map', JSON.stringify(await st()));
  await page.keyboard.press('Space'); await page.waitForTimeout(500);
  console.log('6 play II', JSON.stringify(await st()));
  await page.keyboard.press('Escape'); await page.waitForTimeout(200);
  await page.screenshot({ path: 'shots/flow_pause.png' });
  await page.keyboard.press('KeyN'); await page.waitForTimeout(300);
  console.log('7 N restarts', JSON.stringify(await st()));
  await page.keyboard.press('Escape'); await page.waitForTimeout(200); await page.keyboard.press('KeyQ'); await page.waitForTimeout(300);
  console.log('8 Q map', JSON.stringify(await st()));
  await page.evaluate(() => window.__dweller.setProgress({ beaten: [true, true, true, true, true, false] }));
  await page.evaluate(() => window.__dweller.startLevel(5, true)); await page.waitForTimeout(300);
  await winNow(); await page.waitForTimeout(3200);
  await page.screenshot({ path: 'shots/flow_win6.png' });
  await page.keyboard.press('Enter'); await page.waitForTimeout(1500);
  await page.screenshot({ path: 'shots/flow_fuse.png' });
  await page.waitForTimeout(3500);
  await page.screenshot({ path: 'shots/flow_open.png' });
  console.log('9 fused', JSON.stringify(await st()));
  await page.keyboard.press('Space'); await page.waitForTimeout(400);
  await page.screenshot({ path: 'shots/flow_door.png' });
  console.log('errors', errs.length ? errs : 'none');
  await b.close();
})();
